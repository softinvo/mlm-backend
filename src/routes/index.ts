const router = Router();

// (the test runner makes many sign-ins from one address, so it gets a much higher limit)
const authLimiter = rateLimit({ windowMs: 15 * 60 * 1000, limit: process.env.NODE_TEST_CONTEXT ? 10_000 : 20, standardHeaders: true, legacyHeaders: false });
// Checkout / order actions: generous enough for normal shopping, still bounded.
const uploadLimiter = rateLimit({ windowMs: 15 * 60 * 1000, limit: 60, standardHeaders: true, legacyHeaders: false });
const supportLimiter = rateLimit({ windowMs: 15 * 60 * 1000, limit: 40, standardHeaders: true, legacyHeaders: false });
const contactLimiter = rateLimit({ windowMs: 60 * 60 * 1000, limit: 5, standardHeaders: true, legacyHeaders: false, message: { error: 'Too many messages from this device. Please try again later.' } });
const orderLimiter = rateLimit({ windowMs: 15 * 60 * 1000, limit: 60, standardHeaders: true, legacyHeaders: false });
// Member ID lookups are rate-limited so the ID space can't be scraped.
const lookupLimiter = rateLimit({ windowMs: 15 * 60 * 1000, limit: 40, standardHeaders: true, legacyHeaders: false });
const passwordLimiter = rateLimit({ windowMs: 15 * 60 * 1000, limit: 10, standardHeaders: true, legacyHeaders: false });

router.get('/health', (_req, res) => res.json({ ok: true }));
// Public website (no sign-in)
router.get('/public/catalog', asyncHandler(publicCatalog));
router.get('/public/gallery', asyncHandler(publicGallery));
router.get('/public/site', asyncHandler(publicSite));
router.post('/public/contact', contactLimiter, asyncHandler(submitContact));
